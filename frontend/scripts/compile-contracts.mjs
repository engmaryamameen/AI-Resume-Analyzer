// Compile OpenAPI validators ahead of time so the browser never needs eval or Function.
import fs from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import prettier from "prettier";

const root = new URL("../", import.meta.url);
const contracts = JSON.parse(
  await fs.readFile(new URL("src/lib/response-contracts.json", root), "utf8"),
);
const ajv = new Ajv({ strict: false, validateFormats: false, code: { source: true, esm: true } });
ajv.addSchema({ $id: "api", components: contracts.components });
const exports = {};
contracts.routes.forEach((route, index) => {
  const name = `response${index}`;
  const schema = JSON.parse(
    JSON.stringify(route.schema).replaceAll('"#/components/', '"api#/components/'),
  );
  ajv.addSchema(schema, name);
  exports[name] = name;
});
const target = new URL("src/lib/response-validators.js", root);
const formatting = await prettier.resolveConfig(fileURLToPath(target));
const source = await prettier.format(
  "/* eslint-disable */\n// Generated by scripts/compile-contracts.mjs. Do not edit.\n" +
    standaloneCode(ajv, exports),
  { ...formatting, parser: "babel" },
);
if (process.argv.includes("--check")) {
  if ((await fs.readFile(target, "utf8")) !== source)
    throw new Error("Response validators changed; run node frontend/scripts/compile-contracts.mjs");
} else await fs.writeFile(target, source);
console.log(`Validated ${contracts.routes.length} response contracts in ${fileURLToPath(target)}`);
